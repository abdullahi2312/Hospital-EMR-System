'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const Payment = require('../models/Payment');

const PAYMENT_TEST_SECRET = 'test-only-payment-fingerprint-secret-32-bytes-minimum';
process.env.PAYMENT_FINGERPRINT_SECRET = PAYMENT_TEST_SECRET;
const fingerprintInput = {
  phoneNumber: '+252612345678',
  amount: 25.5,
  currency: 'USD',
  description: 'Clinic service',
  simulateOutcome: 'success'
};

function validPayment(overrides = {}) {
  return new Payment({
    initiatingUser: new mongoose.Types.ObjectId(),
    amount: 25.5,
    currency: 'USD',
    idempotencyKey: `payment-test-${process.pid}`,
    inputFingerprint: Payment.createInputFingerprint(fingerprintInput),
    ...overrides
  });
}

test('HMAC fingerprint is stable for normalized identical inputs and changes with payment input', () => {
  const original = Payment.createInputFingerprint(fingerprintInput);
  const normalizedEquivalent = Payment.createInputFingerprint({
    ...fingerprintInput,
    phoneNumber: ' +252612345678 ',
    currency: ' usd ',
    description: ' Clinic service '
  });
  assert.equal(original, normalizedEquivalent);
  assert.match(original, /^[a-f0-9]{64}$/);
  for (const changed of [
    { ...fingerprintInput, phoneNumber: '+252612345679' },
    { ...fingerprintInput, amount: 25.51 },
    { ...fingerprintInput, currency: 'SOS' },
    { ...fingerprintInput, description: 'Different service' }
  ]) {
    assert.notEqual(Payment.createInputFingerprint(changed), original);
  }
});

test('fingerprint generation fails safely when its dedicated secret is missing or invalid', () => {
  const originalSecret = process.env.PAYMENT_FINGERPRINT_SECRET;
  try {
    delete process.env.PAYMENT_FINGERPRINT_SECRET;
    assert.throws(
      () => Payment.createInputFingerprint(fingerprintInput),
      (error) => error.name === 'PaymentFingerprintConfigurationError' && error.status === 503 &&
        !error.message.includes('PAYMENT_FINGERPRINT_SECRET')
    );
    process.env.PAYMENT_FINGERPRINT_SECRET = 'short';
    assert.throws(() => Payment.createInputFingerprint(fingerprintInput), /configuration is invalid/);
    process.env.PAYMENT_FINGERPRINT_SECRET = 'REPLACE_WITH_A_DISTINCT_RANDOM_SECRET_AT_LEAST_32_CHARACTERS';
    assert.throws(() => Payment.createInputFingerprint(fingerprintInput), /configuration is invalid/);
  } finally {
    process.env.PAYMENT_FINGERPRINT_SECRET = originalSecret;
  }
});

test('creates a valid pending Payment with server-generated identity and timestamps', async () => {
  const before = Date.now();
  const payment = validPayment();
  await payment.validate();
  assert.match(payment.paymentReference, /^pay-[0-9a-f-]{36}$/);
  assert.equal(payment.status, 'pending');
  assert.equal(payment.provider, 'simulated-mobile-money');
  assert.ok(payment.createdAt instanceof Date);
  assert.ok(payment.updatedAt instanceof Date);
  assert.ok(payment.createdAt.getTime() >= before);
  assert.equal(payment.phoneNumber, undefined);
  assert.equal(payment.get('idempotencyKey'), `payment-test-${process.pid}`);
  assert.match(payment.get('inputFingerprint'), /^[a-f0-9]{64}$/);
  assert.equal(payment.toJSON().inputFingerprint, undefined);
  assert.equal(payment.toObject().inputFingerprint, undefined);
});

test('rejects invalid amount, currency, and initial status', async () => {
  for (const amount of [0, -1, NaN, Infinity, 1_000_000.01, 1.001]) {
    await assert.rejects(validPayment({ amount }).validate());
  }
  await assert.rejects(validPayment({ currency: 'EUR' }).validate());
  await assert.rejects(validPayment({ status: 'simulated_success' }).validate(), /pending status/);
  await assert.rejects(validPayment({ status: 'unknown' }).validate());
});

test('rejects caller-supplied payment reference and timestamps on creation', async () => {
  const reference = 'pay-00000000-0000-0000-0000-000000000000';
  await assert.rejects(validPayment({ paymentReference: reference }).validate(), /generated by the server/);
  await assert.rejects(validPayment({ createdAt: new Date(0) }).validate(), /generated by the server/);
  await assert.rejects(validPayment({ updatedAt: new Date(0) }).validate(), /generated by the server/);
});

test('schema declares a unique payment reference and per-user idempotency index', () => {
  const indexes = Payment.schema.indexes();
  assert.ok(indexes.some(([keys, options]) => (
    keys.paymentReference === 1 && options.unique === true
  )));
  assert.ok(indexes.some(([keys, options]) => (
    keys.initiatingUser === 1 && keys.idempotencyKey === 1 && options.unique === true
  )));
});

test('immutable identity fields cannot be changed after document creation', async () => {
  const userId = new mongoose.Types.ObjectId();
  const patientId = new mongoose.Types.ObjectId();
  const payment = validPayment({ initiatingUser: userId, patient: patientId });
  const originalReference = payment.paymentReference;
  const originalCreatedAt = payment.createdAt;

  // Model a document after persistence; Mongoose immutable paths are enforced
  // for hydrated/saved documents, while initial values are set by the creator.
  payment.$isNew = false;
  payment.paymentReference = 'pay-00000000-0000-0000-0000-000000000000';
  payment.initiatingUser = new mongoose.Types.ObjectId();
  payment.patient = new mongoose.Types.ObjectId();
  payment.amount = 900;
  payment.currency = 'SOS';
  payment.provider = 'real-provider';
  payment.idempotencyKey = 'another-key';
  payment.description = 'Changed';
  payment.createdAt = new Date(0);

  assert.equal(payment.paymentReference, originalReference);
  assert.equal(String(payment.initiatingUser), String(userId));
  assert.equal(String(payment.patient), String(patientId));
  assert.equal(payment.amount, 25.5);
  assert.equal(payment.currency, 'USD');
  assert.equal(payment.provider, 'simulated-mobile-money');
  assert.equal(payment.get('idempotencyKey'), `payment-test-${process.pid}`);
  assert.equal(payment.description, undefined);
  assert.equal(payment.createdAt.getTime(), originalCreatedAt.getTime());
});

test('strict mode rejects unknown fields and sensitive payment credentials', () => {
  for (const field of ['phoneNumber', 'pin', 'otp', 'password', 'providerReference', 'transactionId', 'unknown']) {
    assert.throws(() => validPayment({ [field]: 'sensitive-or-unsupported' }), mongoose.Error.StrictModeError);
  }
});

test('same idempotency value is user-scoped in the declared compound index', () => {
  const firstUser = new mongoose.Types.ObjectId();
  const secondUser = new mongoose.Types.ObjectId();
  const key = 'shared-idempotency-key';
  const first = validPayment({ initiatingUser: firstUser, idempotencyKey: key });
  const second = validPayment({ initiatingUser: secondUser, idempotencyKey: key });
  assert.equal(first.get('idempotencyKey'), second.get('idempotencyKey'));
  assert.notEqual(String(first.initiatingUser), String(second.initiatingUser));
  // Actual duplicate enforcement depends on MongoDB building the declared unique index.
});

test('status transition helper uses a pending-state conditional update', () => {
  const reference = 'pay-00000000-0000-0000-0000-000000000000';
  const query = Payment.transitionStatus(reference, 'simulated_success');
  assert.deepEqual(query.getFilter(), { paymentReference: reference, status: 'pending' });
  assert.deepEqual(query.getUpdate(), { $set: { status: 'simulated_success' } });
  assert.throws(() => Payment.transitionStatus(reference, 'pending'), /simulated_success or simulated_failed/);
});

test('status changes outside the allowed atomic path and bulk status changes are rejected', async () => {
  const reference = 'pay-00000000-0000-0000-0000-000000000000';
  await assert.rejects(
    Payment.findOneAndUpdate(
      { paymentReference: reference, status: 'simulated_success' },
      { $set: { status: 'simulated_failed' } }
    ).exec(),
    /atomically from pending/
  );
  await assert.rejects(
    Payment.updateMany({ status: 'pending' }, { $set: { status: 'simulated_success' } }).exec(),
    /Bulk payment status updates are not allowed/
  );
});
