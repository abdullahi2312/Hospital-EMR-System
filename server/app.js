const express = require('express');
const healthRoutes = require('./routes/health.routes');
const authRoutes = require('./routes/auth.routes');
const protectedRoutes = require('./routes/protected.routes');
const adminRoutes = require('./routes/admin.routes');
const accessLogRoutes = require('./routes/access-log.routes');
const auditLogRoutes = require('./routes/audit-log.routes');
const userManagementRoutes = require('./routes/user-management.routes');
const patientRoutes = require('./routes/patient.routes');
const patientTimelineRoutes = require('./routes/patient-timeline.routes');
const breakGlassRoutes = require('./routes/break-glass.routes');
const encounterRoutes = require('./routes/encounter.routes');
const encounterManagementRoutes = require('./routes/encounter-management.routes');
const labRoutes = require('./routes/lab.routes');
const pharmacyRoutes = require('./routes/pharmacy.routes');
const consentRoutes = require('./routes/consent.routes');
const referralRoutes = require('./routes/referral.routes');
const paymentRoutes = require('./routes/payment.routes');
const fhirRoutes = require('./routes/fhir.routes');
const notificationRoutes = require('./routes/notification.routes');
const patientPortalRoutes = require('./routes/patient-portal.routes');
const departmentRoutes = require('./routes/department.routes');
const notFound = require('./middleware/not-found');
const errorHandler = require('./middleware/error-handler');
const securityHeaders = require('./middleware/security-headers.middleware');
const localization = require('./middleware/localization.middleware');

const app = express();

app.use(securityHeaders);
app.use(localization);
app.use(express.json());
app.use('/api', healthRoutes);
app.use('/api/auth', authRoutes);
app.use('/api/protected', protectedRoutes);
app.use('/api/admin', adminRoutes);
app.use('/api/admin/access-logs', accessLogRoutes);
app.use('/api/admin/audit-logs', auditLogRoutes);
app.use('/api/admin/users', userManagementRoutes);
app.use('/api/patients', patientRoutes);
app.use('/api/patients', patientTimelineRoutes);
app.use('/api/patients', breakGlassRoutes);
app.use('/api/encounters', encounterRoutes);
app.use('/api/encounters', encounterManagementRoutes);
app.use('/api/encounters', labRoutes.encounterRouter);
app.use('/api/lab', labRoutes);
app.use('/api/pharmacy', pharmacyRoutes);
app.use('/api/consents', consentRoutes);
app.use('/api/referrals', referralRoutes);
app.use('/api/payments', paymentRoutes);
app.use('/api/fhir', fhirRoutes);
app.use('/api/notifications', notificationRoutes);
app.use('/api/patient-portal', patientPortalRoutes);
app.use('/api/departments', departmentRoutes);
app.use(notFound);
app.use(errorHandler);

module.exports = app;
